#!/usr/bin/env python3
"""Generate a small override SDF for the TDC carry chain's addf_1 cells.

Icarus Verilog's $sdf_annotate cannot match the COND-qualified IOPATH
entries that this PDK's gf180mcu_fd_sc_mcu7t5v0__addf_1 model uses for every
arc (confirmed: every compound/multi-input cell in the generated SDF -
aoi21/22/222, oai21/22/211, mux2, dffrnq, addf_1 - uses COND entries; plain
gates like inv/buf/nand2 don't and annotate fine). Icarus instead applies
the cell's plain unconditional IOPATH, which this PDK always writes as a
0.000ns placeholder alongside the real COND-qualified values, so the carry
chain shows zero delay in gate-level simulation.

Since each chain stage permanently ties A=0, B=1 (see src/carry_chain.sv,
enforced in STA via set_case_analysis in src/impl.sdc), only the
"A===1'b0 && B===1'b1" CI->CO arc can ever be active. This script pulls
that arc's real delay out of the real, generated SDF and re-emits it as a
plain unconditional IOPATH in a small standalone SDF. tb.v applies this
with a second $sdf_annotate call after the main one; SDF re-annotation of
an already-matched path overwrites it (last match wins), so this overrides
only the 31 carry-chain CI->CO paths and leaves everything else untouched.
"""
import re
import sys

SOURCE_SDF = "../runs/wokwi/final/sdf/nom_tt_025C_3v30/tt_um_bbawj_volt_profile__nom_tt_025C_3v30.sdf"
OUTPUT_SDF = "addf_override.sdf"

CELL_RE = re.compile(
    r'\(CELL\n'
    r'\s*\(CELLTYPE "gf180mcu_fd_sc_mcu7t5v0__addf_1"\)\n'
    r'\s*\(INSTANCE (tdc_\\/cc\\/genblk1\\\[\d+\\\]\\\.fa)\)\n'
    r'\s*\(DELAY\n'
    r'\s*\(ABSOLUTE\n'
    r'(.*?)'
    r'\n\s*\)\n\s*\)\n \)',
    re.S,
)

COND_CI_CO_RE = re.compile(
    r"COND A===1'b0 && B===1'b1\s*\n\s*\(IOPATH CI CO (\([^)]*\) \([^)]*\))\)"
)


def main():
    with open(SOURCE_SDF) as f:
        text = f.read()

    cells = CELL_RE.findall(text)
    if not cells:
        sys.exit(f"no addf_1 CELL blocks found in {SOURCE_SDF}")

    entries = []
    for instance, body in cells:
        m = COND_CI_CO_RE.search(body)
        if not m:
            sys.exit(f"could not find A=0,B=1 CI->CO delay for {instance}")
        entries.append((instance, m.group(1)))

    with open(OUTPUT_SDF, "w") as f:
        f.write("// Generated by gen_addf_override_sdf.py.\n")
        f.write(f"// CI->CO delays quoted from {SOURCE_SDF},\n")
        f.write(
            "// the \"COND A===1'b0 && B===1'b1\" arc of each genblk1[N].fa"
            " (gf180mcu_fd_sc_mcu7t5v0__addf_1) instance - the only arc that\n"
        )
        f.write(
            "// can ever be active given A=0, B=1 tied per stage. See the"
            " module docstring above for why this override exists.\n"
        )
        f.write("(DELAYFILE\n")
        f.write(' (SDFVERSION "3.0")\n')
        f.write(' (DESIGN "tt_um_bbawj_volt_profile")\n')
        f.write(' (VENDOR "tt-volt")\n')
        f.write(' (PROGRAM "gen_addf_override_sdf.py")\n')
        f.write(" (DIVIDER .)\n")
        f.write(" (TIMESCALE 1ns)\n")
        for instance, delay in entries:
            f.write(" (CELL\n")
            f.write('  (CELLTYPE "gf180mcu_fd_sc_mcu7t5v0__addf_1")\n')
            f.write(f"  (INSTANCE {instance})\n")
            f.write("  (DELAY\n")
            f.write("   (ABSOLUTE\n")
            f.write(f"    (IOPATH CI CO {delay})\n")
            f.write("   )\n")
            f.write("  )\n")
            f.write(" )\n")
        f.write(")\n")

    print(f"wrote {len(entries)} overrides to {OUTPUT_SDF}")


if __name__ == "__main__":
    main()
